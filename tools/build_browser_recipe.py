#!/usr/bin/env python3
"""Compile the verified direct builder's owned writes to a browser recipe.

Private input required. No firmware outputs are written. Factory-matching spans
are represented by copy operations, zero runs by fill operations. All direct
builder guards, cache/source pins and final validations run before export.
"""
import argparse
import base64
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'firmware_builder/direct'))
from build import build
from core import Component, FACTORY_SHA256, FINAL_SHA256, sha


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('factory', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    factory = args.factory.read_bytes()
    captured = {}
    original_render = Component.render

    def capture(component):
        result = original_render(component)
        captured[component.name] = component
        return result

    Component.render = capture
    try:
        output, report = build(factory, ROOT / 'firmware_builder/direct/cache')
    finally:
        Component.render = original_render

    # Index every 8-byte factory sequence. Greedy copies remove factory-derived
    # tables and code from the published recipe, including relocated sequences.
    lookup = {}
    for at in range(len(factory) - 7):
        lookup.setdefault(factory[at:at+8], at)

    def encode(data):
        ops, literal = [], bytearray()

        def flush():
            if literal:
                ops.append(['literal', base64.b64encode(literal).decode('ascii')])
                literal.clear()

        at = 0
        while at < len(data):
            if data[at:at+8] == bytes(8):
                end = at + 8
                while end < len(data) and data[end] == 0:
                    end += 1
                flush()
                ops.append(['zero', end-at])
                at = end
            elif at+8 <= len(data) and (source := lookup.get(data[at:at+8])) is not None:
                size = 8
                while at+size < len(data) and source+size < len(factory) and data[at+size] == factory[source+size]:
                    size += 1
                flush()
                ops.append(['copy', source, size])
                at += size
            else:
                literal.append(data[at])
                at += 1
        flush()
        return ops

    components = []
    for name in ('QNX', 'PIC'):
        component = captured[name]
        writes = []
        for write, receipt in zip(sorted(component.writes, key=lambda w: w.offset), component.receipt()):
            writes.append({**receipt, 'source': write.source, 'ops': encode(write.data)})
        components.append({'name': name, 'factory_size': len(component.factory),
                           'factory_sha256': sha(component.factory),
                           'final_size': component.final_size, 'writes': writes})
    # Pin all generator inputs, not just the historical cache manifest.
    direct = ROOT / 'firmware_builder/direct'
    sources = {str(p.relative_to(ROOT)): sha(p.read_bytes()) for p in sorted(direct.rglob('*'))
               if p.is_file() and '__pycache__' not in p.parts}
    recipe = {'format': 1, 'factory_sha256': FACTORY_SHA256, 'factory_size': len(factory),
              'final_sha256': FINAL_SHA256, 'final_size': len(output),
              'sources': sources, 'components': components}
    payload = json.dumps(recipe, sort_keys=True, separators=(',', ':'))
    digest = sha(payload.encode())
    script = '// Generated by tools/build_browser_recipe.py; MIT, see ../LICENSE and ../NOTICE.\n'
    script += 'globalThis.PX_RECIPE_JSON = ' + json.dumps(payload) + ';\n'
    target = ROOT / 'website/recipe.js'
    pin = ROOT / 'website/recipe-pin.js'
    pin_text = '// Generated recipe integrity pin.\n' + f'globalThis.PX_RECIPE_SHA256 = "{digest}";\n'
    for path, content in ((target, script), (pin, pin_text)):
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Recipe drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    print(json.dumps({'status': 'PASS', 'recipe_sha256': digest,
                      'writes': sum(len(c['writes']) for c in components),
                      'factory_sha256': sha(factory), 'final_sha256': sha(output),
                      'final_size': len(output), 'direct_checks': report['checks']}, indent=2))


if __name__ == '__main__':
    main()
