BASE=0x9d0002a0
STATE=0x80057aa0

class Asm:

    def __init__(self):
        self.rows = []
        self.labels = {}
        self.functions = []

    def label(self, n):
        assert n not in self.labels
        self.labels[n] = BASE + 4 * len(self.rows)

    def emit(self, *r):
        self.rows.append(r)

    def block(self, rows):
        for r in rows:
            self.emit(*r)

    def state(self, r='t9'):
        self.emit('lui', r, 32773)
        self.emit('ori', r, r, 31392)

    def move(self, d, s):
        self.emit('addu', d, s, 'zero')

    def li(self, d, n):
        self.emit('addiu', d, 'zero', n)

    def branch(self, op, r, s, target, delay=('nop',)):
        self.emit(op, r, s, target)
        self.emit(*delay)

    def jump(self, name, delay=('nop',)):
        self.emit('j', name)
        self.emit(*delay)

    def call(self, name, delay=('nop',)):
        self.emit('jal', name)
        self.emit(*delay)

    def ret(self):
        self.emit('jr', 'ra')
        self.emit('nop')

    def func(self, name, rows=None):
        self.functions.append(name)
        self.label(name)
        self.block(rows or [])

    def save(self, regs, extra=0):
        n = (16 + extra + 4 * len(regs) + 7) // 8 * 8
        self.emit('addiu', 'sp', 'sp', -n)
        for i, r in enumerate(regs):
            self.emit('sw', r, 'sp', n - 4 * (i + 1))
        return n

    def restore(self, regs, n):
        for i, r in enumerate(regs):
            self.emit('lw', r, 'sp', n - 4 * (i + 1))
        self.emit('addiu', 'sp', 'sp', n)

    def compact(self):
        before = len(self.rows)
        labels = {k: (v - BASE) // 4 for k, v in self.labels.items()}
        i = 1
        while i + 1 < len(self.rows):
            control = self.rows[i]
            prev = self.rows[i - 1]
            op = control[0]
            entries = set(labels.values())
            if op not in ('j', 'jal', 'jr', 'beq', 'bne') or self.rows[i + 1] != ('nop',) or any((j in entries for j in (i - 1, i, i + 1))):
                i += 1
                continue
            if i > 1 and self.rows[i - 2][0] in ('j', 'jal', 'jr', 'beq', 'bne'):
                i += 1
                continue
            if prev[0] not in ('addu', 'subu', 'sll', 'srl', 'slt', 'sltu', 'xor', 'or', 'and', 'addiu', 'lui', 'ori', 'andi', 'sltiu', 'sw', 'sh', 'sb', 'lw', 'lhu', 'lbu'):
                i += 1
                continue
            written = set() if prev[0] in ('sw', 'sh', 'sb') else {prev[1]}
            readcond = set(control[1:3]) if op in ('beq', 'bne') else {control[1]} if op == 'jr' else set()
            if written & readcond or (op == 'jal' and 'ra' in prev[1:]):
                i += 1
                continue
            self.rows[i - 1:i + 2] = [control, prev]
            labels = {k: v - 1 if v >= i else v for k, v in labels.items()}
            i = max(1, i - 1)
        self.labels = {k: BASE + 4 * v for k, v in labels.items()}
        return before - len(self.rows)

    def bytes(self):
        return emit(self.rows, BASE, self.labels)

